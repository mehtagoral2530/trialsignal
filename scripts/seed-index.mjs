// Generates shared/index-seed.js: the curated trials as BM25 documents, bundled into the Worker
// so search works even when the Pages snapshot index can't be fetched.
import { writeFileSync } from "node:fs";
import { loadAppData } from "./lib-appdata.mjs";
const root = new URL("..", import.meta.url).pathname;
const { TRIALS } = loadAppData(root);
const docs = TRIALS.map((t) => ({
  nct: t.id, title: t.title, acronym: t.short, status: (t.status || "").toUpperCase().replace(/[ ,]+/g, "_") || null,
  phase: (t.phase || "").toUpperCase().replace(/\s+/g, ""), conditions: [t.condition], interventions: [t.intervention],
  summary: `${t.question} ${t.plainPop}`, lastUpdate: null,
}));
writeFileSync(`${root}/shared/index-seed.js`, "// Generated by scripts/seed-index.mjs. Do not edit.\nexport const SEED_DOCS = " + JSON.stringify(docs, null, 1) + ";\n");
console.log(`seed: ${docs.length} docs`);
